CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  eid TEXT NOT NULL UNIQUE,
  ts INTEGER NOT NULL,
  cls TEXT NOT NULL,
  alias TEXT NOT NULL,
  topic TEXT NOT NULL,
  sid TEXT NOT NULL,
  type TEXT NOT NULL,
  data TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS events_by_class ON events (cls, topic, ts);
